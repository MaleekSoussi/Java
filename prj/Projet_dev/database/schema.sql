DROP TABLE IF EXISTS inscription CASCADE;
DROP TABLE IF EXISTS cours       CASCADE;
DROP TABLE IF EXISTS enfant      CASCADE;
DROP TABLE IF EXISTS mouvement   CASCADE;
DROP TABLE IF EXISTS salle       CASCADE;
DROP TABLE IF EXISTS niveau      CASCADE;
DROP TABLE IF EXISTS utilisateur CASCADE;

CREATE TABLE utilisateur (
    id_utilisateur   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom              VARCHAR(100)  NOT NULL,
    prenom           VARCHAR(100)  NOT NULL,
    email            VARCHAR(255)  NOT NULL UNIQUE,
    mot_de_passe     VARCHAR(255)  NOT NULL,
    role             VARCHAR(20)   NOT NULL DEFAULT 'PARENT' CHECK (role IN ('PARENT', 'ADMIN')),
    mode_paiement    VARCHAR(50),
    nombre_paiements INTEGER       CHECK (nombre_paiements >= 1),
    solde_restant    NUMERIC(10,2) NOT NULL DEFAULT 0
);

CREATE TABLE mouvement (
    id_mouvement    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_utilisateur  BIGINT        NOT NULL REFERENCES utilisateur(id_utilisateur) ON DELETE CASCADE,
    date_mouvement  DATE          NOT NULL DEFAULT CURRENT_DATE,
    montant         NUMERIC(10,2) NOT NULL CHECK (montant > 0),
    moyen_paiement  VARCHAR(50)
);

CREATE TABLE niveau (
    id_niveau  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    libelle    VARCHAR(100)  NOT NULL UNIQUE,
    montant    NUMERIC(10,2) NOT NULL CHECK (montant >= 0)
);

CREATE TABLE salle (
    id_salle  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom       VARCHAR(100) NOT NULL UNIQUE,
    capacite  INTEGER      NOT NULL CHECK (capacite > 0)
);

CREATE TABLE enfant (
    id_enfant       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom             VARCHAR(100) NOT NULL,
    prenom          VARCHAR(100) NOT NULL,
    date_naissance  DATE,
    etablissement   VARCHAR(150),
    id_utilisateur  BIGINT NOT NULL REFERENCES utilisateur(id_utilisateur) ON DELETE CASCADE,
    id_niveau       BIGINT REFERENCES niveau(id_niveau) ON DELETE SET NULL
);

CREATE TABLE cours (
    id_cours           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    jour               VARCHAR(10) NOT NULL
                       CHECK (jour IN ('LUNDI','MARDI','MERCREDI','JEUDI','VENDREDI','SAMEDI','DIMANCHE')),
    heure_debut        TIME    NOT NULL,
    heure_fin          TIME    NOT NULL,
    places_disponibles INTEGER NOT NULL DEFAULT 0 CHECK (places_disponibles >= 0),
    id_salle           BIGINT  REFERENCES salle(id_salle)   ON DELETE SET NULL,
    id_niveau          BIGINT  REFERENCES niveau(id_niveau) ON DELETE SET NULL,
    CHECK (heure_fin > heure_debut)
);

-- Association Enfant *-* Cours
CREATE TABLE inscription (
    id_enfant        BIGINT NOT NULL REFERENCES enfant(id_enfant) ON DELETE CASCADE,
    id_cours         BIGINT NOT NULL REFERENCES cours(id_cours)   ON DELETE CASCADE,
    date_inscription DATE   NOT NULL DEFAULT CURRENT_DATE,
    PRIMARY KEY (id_enfant, id_cours)
);

CREATE INDEX idx_mouvement_utilisateur ON mouvement(id_utilisateur);
CREATE INDEX idx_enfant_utilisateur    ON enfant(id_utilisateur);
CREATE INDEX idx_enfant_niveau         ON enfant(id_niveau);
CREATE INDEX idx_cours_salle           ON cours(id_salle);
CREATE INDEX idx_cours_niveau          ON cours(id_niveau);
CREATE INDEX idx_inscription_cours     ON inscription(id_cours);

