-- Schema

DROP SCHEMA IF EXISTS public CASCADE;

CREATE SCHEMA public;

-------

-- Tables


CREATE TABLE subvention(
   id BIGINT GENERATED BY DEFAULT AS IDENTITY,
   annee INTEGER NOT NULL CONSTRAINT subvention_annee_entre_2000_et_2100 CHECK (annee BETWEEN 2000 AND 2100),
   organisme VARCHAR(45)  NOT NULL CONSTRAINT subvention_organisme_pas_vide CHECK (TRIM(organisme) <>''),
   nom VARCHAR(60)  NOT NULL CONSTRAINT subvention_nom_pas_vide CHECK (TRIM(nom) <>''),
   montant NUMERIC(12,2) NOT NULL CONSTRAINT subvention_montant_positif CHECK (montant > 0),
   disponible NUMERIC(12,2) NOT NULL CONSTRAINT subvention_disponible_positif_ou_nul CHECK (disponible >= 0),
   PRIMARY KEY(id)
);

CREATE TABLE comptable(
   id BIGINT GENERATED BY DEFAULT AS IDENTITY,
   nom VARCHAR(30)  NOT NULL CONSTRAINT comptable_nom_pas_vide CHECK (TRIM(nom) <>''),
   prenom VARCHAR(30)  NOT NULL CONSTRAINT comptable_prenom_pas_vide CHECK (TRIM(prenom) <>''),
   email VARCHAR(50)  NOT NULL CONSTRAINT comptable_email_pas_vide CHECK (TRIM(email) <>''),
   PRIMARY KEY(id),
   UNIQUE(email)
);

CREATE TABLE depense(
   id BIGINT GENERATED BY DEFAULT AS IDENTITY,
   objet VARCHAR(50)  NOT NULL CONSTRAINT depense_objet_pas_vide CHECK (TRIM(objet) <>''),
   date_depense DATE NOT NULL,
   montant NUMERIC(12,2) NOT NULL CONSTRAINT depense_montant_positif CHECK (montant > 0),
   reliquat NUMERIC(12,2) NOT NULL CONSTRAINT depense_reliquat_positif_ou_nul CHECK (reliquat >= 0),
   comptable_id BIGINT,
   PRIMARY KEY(id),
   FOREIGN KEY(comptable_id) REFERENCES comptable(id)
);

CREATE TABLE subvention_comptable(
   subvention_id BIGINT,
   comptable_id BIGINT,
   PRIMARY KEY(subvention_id, comptable_id),
   FOREIGN KEY(subvention_id) REFERENCES subvention(id),
   FOREIGN KEY(comptable_id) REFERENCES comptable(id)
);

CREATE TABLE compte(
   id BIGINT GENERATED BY DEFAULT AS IDENTITY,
   nom VARCHAR(25)  NOT NULL CONSTRAINT compte_nom_pas_vide CHECK (TRIM(nom) <>''),
   empreinte_mdp VARCHAR(68)  NOT NULL CONSTRAINT compte_empreinte_mdp_pas_vide CHECK (TRIM(empreinte_mdp) <>''),
   role_admin BOOLEAN NOT NULL DEFAULT FALSE,
   comptable_id BIGINT,
   PRIMARY KEY(id),
   UNIQUE(comptable_id),
   UNIQUE(nom),
   FOREIGN KEY(comptable_id) REFERENCES comptable(id) ON DELETE CASCADE
);

CREATE TABLE imputation(
   depense_id BIGINT,
   subvention_id BIGINT,
   montant NUMERIC(12,2) NOT NULL CONSTRAINT imputation_montant_positif CHECK (montant > 0),
   PRIMARY KEY(depense_id, subvention_id),
   FOREIGN KEY(depense_id) REFERENCES depense(id),
   FOREIGN KEY(subvention_id) REFERENCES subvention(id)
);
